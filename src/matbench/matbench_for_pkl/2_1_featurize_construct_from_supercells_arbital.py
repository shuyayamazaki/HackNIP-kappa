#!/usr/bin/env python3
"""
Featurize supercells built from arbitrary CIF strings (no splits/properties), producing
per-layer ORB2 features and a compact pickle bundle.

This script is a slimmed-down variant of 2_featurize_construct_from_supercells.py,
targeting the metadata/trajectories generated by 1_1_build_supercelss_from_pkl_arbital.py:
  - Expects <slug>_all_XPS.traj under <data_root>/structures
  - Expects <slug>_meta.pkl under <data_root>/metadata with matching ids order
Outputs:
  - NPY feature arrays per layer under <data_root>/feat_<mlip>/npy/
  - A bundled pickle <slug>_XPS_<mlip>.pkl with atoms + per-layer features
"""

import argparse
import pickle
from pathlib import Path
from typing import Dict, List, Sequence

import numpy as np
import torch
from ase.io import read
from tqdm import tqdm

from orb_models.forcefield import atomic_system, pretrained


def default_data_root() -> Path:
    return Path(__file__).resolve().parent / "benchmark_data"


def prepare_dirs(data_root: Path, mlip: str) -> Dict[str, Path]:
    structures_dir = data_root / "structures"
    meta_dir = data_root / "metadata"
    feat_dir = data_root / f"feat_{mlip}"
    npy_dir = feat_dir / "npy"

    for p in [structures_dir, meta_dir, feat_dir, npy_dir]:
        p.mkdir(parents=True, exist_ok=True)

    return {
        "structures": structures_dir,
        "meta": meta_dir,
        "feat": feat_dir,
        "npy": npy_dir,
    }


def get_graph_features(atoms, model, layer_until: int, device: str) -> np.ndarray:
    """Run ORB featurization up to a given layer for a single structure."""
    graph = atomic_system.ase_atoms_to_atom_graphs(atoms, device=device)
    graph = model.featurize_edges(graph)
    graph = model.featurize_nodes(graph)
    graph = model._encoder(graph)

    for gnn in model.gnn_stacks[:layer_until]:
        graph = gnn(graph)

    graph = model._decoder(graph)
    return graph.node_features["feat"].mean(dim=0).cpu().numpy()


def set_seed(seed: int = 42) -> None:
    """Deterministic seeds for reproducibility."""
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def compute_features(
    slug: str,
    atoms_list: Sequence,
    model,
    device: str,
    npy_dir: Path,
    layers: Sequence[int],
    overwrite: bool = False,
) -> None:
    key = "XPS"
    for layer in layers:
        npy_path = npy_dir / f"{slug}_all_{key}_l{layer}.npy"
        if npy_path.exists() and not overwrite:
            print(f"[INFO] Skip layer {layer}: cached {npy_path.name}")
            continue

        layer_features = [
            get_graph_features(atoms, model, layer_until=layer, device=device)
            for atoms in tqdm(atoms_list, desc=f"[{slug}] featurizing layer {layer:02d}")
        ]
        layer_array = np.asarray(layer_features, dtype=np.float32)
        np.save(npy_path, layer_array)
        print(f"[OK] Saved features: {npy_path}")

        del layer_features
        del layer_array
        if torch.cuda.is_available():
            torch.cuda.empty_cache()


def build_bundle(
    slug: str,
    meta_all: Dict,
    atoms_all: List,
    mlip: str,
    feat_dir: Path,
    npy_dir: Path,
    layers: Sequence[int],
) -> None:
    key = "XPS"
    key_lower = key.lower()

    data_payload = dict(meta_all)
    data_payload[f"{key_lower}_atoms"] = atoms_all

    meta_path = feat_dir.parent / "metadata" / f"{slug}_meta.pkl"
    data_path = meta_path.with_name(meta_path.name.replace("_meta.pkl", "_data.pkl"))

    with open(data_path, "wb") as dp:
        pickle.dump(data_payload, dp)
    print(f"[OK] Saved data payload: {data_path}")

    feat_payload = dict(data_payload)
    for layer in layers:
        npy_path = npy_dir / f"{slug}_all_{key}_l{layer}.npy"
        feat_payload[f"{key}_{layer}"] = np.load(npy_path)

    feat_path = feat_dir / f"{slug}_{key}_{mlip}.pkl"
    with open(feat_path, "wb") as fp:
        pickle.dump(feat_payload, fp)
    print(f"[OK] Saved feature bundle: {feat_path}")


def parse_layers(arg: str) -> List[int]:
    layers: List[int] = []
    for tok in arg.split(","):
        tok = tok.strip()
        if not tok:
            continue
        if not tok.isdigit():
            raise ValueError(f"Invalid layer value: '{tok}'")
        layers.append(int(tok))
    if not layers:
        raise ValueError("No valid layers provided.")
    return sorted(set(layers))


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Featurize ORB supercells (no splits/properties) and assemble per-layer bundles."
    )
    parser.add_argument("--slug", required=True, help="Dataset identifier, e.g., arbitrary_cif_set.")
    parser.add_argument(
        "--data-root",
        type=Path,
        default=default_data_root(),
        help="Benchmark data root (default: ./benchmark_data next to this script).",
    )
    parser.add_argument("--mlip", default="orb2", help="MLIP tag used for directory naming.")
    parser.add_argument(
        "--layers",
        default=",".join(str(i) for i in range(1, 16)),
        help="Comma-separated list of layers to compute (default: 1-15).",
    )
    parser.add_argument(
        "--device",
        default="auto",
        help="Device for ORB inference (auto|cpu|cuda:0 ...).",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Recompute features even if npy files already exist.",
    )
    args = parser.parse_args()

    layers = parse_layers(args.layers)

    data_root = args.data_root.resolve()
    dirs = prepare_dirs(data_root, args.mlip)

    structures_all_path = dirs["structures"] / f"{args.slug}_all_XPS.traj"
    meta_all_path = dirs["meta"] / f"{args.slug}_meta.pkl"
    if not structures_all_path.exists():
        raise FileNotFoundError(f"Supercell trajectory not found: {structures_all_path}")
    if not meta_all_path.exists():
        raise FileNotFoundError(f"Metadata pickle not found: {meta_all_path}")

    with open(meta_all_path, "rb") as mf:
        meta_all = pickle.load(mf)

    print(f"[INFO] Loading supercells from {structures_all_path}")
    atoms_list = list(read(str(structures_all_path), index="::"))
    print(f"[INFO] Loaded {len(atoms_list)} structures.")

    ids_all = [str(idx) for idx in meta_all.get("ids", [])]
    if len(ids_all) != len(atoms_list):
        raise ValueError(
            f"Mismatch between metadata ids ({len(ids_all)}) and structures ({len(atoms_list)})."
        )

    set_seed()

    device = args.device
    if device == "auto":
        device = "cuda:0" if torch.cuda.is_available() else "cpu"
    print(f"[INFO] Using device={device}")

    orbff = pretrained.orb_v2(device=device)
    orbff.model.eval()

    compute_features(
        slug=args.slug,
        atoms_list=atoms_list,
        model=orbff.model,
        device=device,
        npy_dir=dirs["npy"],
        layers=layers,
        overwrite=args.overwrite,
    )

    build_bundle(
        slug=args.slug,
        meta_all=meta_all,
        atoms_all=atoms_list,
        mlip=args.mlip,
        feat_dir=dirs["feat"],
        npy_dir=dirs["npy"],
        layers=layers,
    )

    print("[DONE] Featurization and bundle construction complete.")


if __name__ == "__main__":
    main()
